"""Cross-skill contract tests for pax-* family.

Every contract is a function ``(family_root: Path) -> list[str]`` returning
violation messages. Empty list = pass.

All contracts resolve the family's single-source-of-truth files from
``family_root`` (never from the tool's install location), so a family
generated by ``pax-forge init`` is checked against its own schema/versions.
"""
from __future__ import annotations

import json as _json
import re as _re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable, Iterable

import jsonschema

from pax.forge import loader
from pax.forge.validator import _split_frontmatter

ContractFn = Callable[[Path], list[str]]

_CONTRACTS: dict[str, ContractFn] = {}


def register_contract(name: str):
    def deco(fn: ContractFn) -> ContractFn:
        _CONTRACTS[name] = fn
        return fn
    return deco


def list_contracts() -> list[str]:
    return sorted(_CONTRACTS.keys())


@dataclass
class ContractReport:
    ok: bool = True
    failures: list[str] = field(default_factory=list)
    passes: list[str] = field(default_factory=list)

    def add_pass(self, name: str) -> None:
        self.passes.append(name)

    def add_fail(self, name: str, messages: list[str]) -> None:
        self.ok = False
        for m in messages:
            self.failures.append(f"[{name}] {m}")


def run_all_contracts(family_root: Path) -> ContractReport:
    report = ContractReport()
    for name, fn in _CONTRACTS.items():
        try:
            violations = fn(family_root)
        except Exception as exc:
            report.add_fail(name, [f"contract raised: {exc!r}"])
            continue
        if violations:
            report.add_fail(name, violations)
        else:
            report.add_pass(name)
    return report


def _iter_skill_dirs(family_root: Path) -> Iterable[Path]:
    skills_dir = family_root / "skills"
    if not skills_dir.exists():
        return
    for child in skills_dir.iterdir():
        if child.is_dir() and (child / "SKILL.md").exists():
            yield child


def _root(family_root: Path) -> Path | None:
    """A partial fixture directory is not a family root: fall back to the
    tool's own family so contracts can still be exercised against it."""
    return loader.resolve_family_root(family_root)


def _skill_docs(family_root: Path) -> Iterable[tuple[str, dict | None, str]]:
    """Yield (skill_name, frontmatter, body) for every skill."""
    for skill_dir in _iter_skill_dirs(family_root):
        text = (skill_dir / "SKILL.md").read_text(encoding="utf-8")
        fm, body = _split_frontmatter(text)
        name = (fm or {}).get("name") or skill_dir.name
        yield name, fm, body


# 元数据字段：这里的 pax-* 提及是「这条记录适用于谁 / 来源于哪次会话」，
# 不是「本 skill 调用了谁」。把它们算进调用图会让no-cycles 与
# layer-call-legality 报出并不存在的环与非法方向。
#
# 典型误报：pax-evolve 的经验条目 E101-E104 里
# `applies_to: ["pax-plan P2 / P7", "pax-execute E3 / E4"]`
# 声明的是经验的适用范围，被扫成 evolve -> plan / evolve -> execute 的调用边。
_METADATA_FIELD_RE = _re.compile(
    r"^\s*(?:-\s*)?("
    r"applies_to|source|statement|rationale|ab_baseline\w*|"
    r"ab_candidate_count|ab_status|ab_notes|deprecated_by|"
    r"created_at|updated_at|promote_recommendation|createdBy|updatedBy"
    r")\s*:",
    _re.M,
)
_LIST_ITEM_RE = _re.compile(r"^\s*-\s")


def _indent_of(line: str) -> int:
    return len(line) - len(line.lstrip(" \t"))


def strip_metadata_fields(body: str) -> str:
    """移除 YAML 元数据字段**及其值**，保留其余正文。

    必须连值一起删，否则误报原样存在：

        applies_to:                <- 删这行
          - "pax-plan P2 / P7"       <- 这行也要删，否则仍被扫成调用边

    三种值形态都要处理：
    - 行内数组：``applies_to: ["pax-execute E4/E8"]``
    - 缩进列表：``applies_to:`` 换行后跟 ``- "..."``
    - block scalar：``rationale: |`` 换行后的缩进正文

    按行剔除而非整块删除：经验条目里元数据与自由文本交错，整块删会
    连带丢掉真实声明（如 description 的「由 pax-orchestrate 委托调用」）。
    """
    lines = body.split("\n")
    kept: list[str] = []
    i = 0
    n = len(lines)

    while i < n:
        line = lines[i]
        if _METADATA_FIELD_RE.match(line):
            i += 1
            # 行内数组：值就在本行，随字段名一起被丢弃
            if _re.search(r":\s*[|>]\s*$", line):
                # block scalar：吃掉后续所有比字段更深的缩进行
                field_indent = _indent_of(line)
                while i < n:
                    nxt = lines[i]
                    if nxt.strip() and _indent_of(nxt) > field_indent:
                        i += 1
                    else:
                        break
            else:
                # 缩进列表：吃掉紧跟其后、同缩进或更深的 `- ` 项
                field_indent = _indent_of(line)
                while i < n:
                    nxt = lines[i]
                    if not nxt.strip():
                        break
                    ind = _indent_of(nxt)
                    if ind <= field_indent:
                        break
                    if _LIST_ITEM_RE.match(nxt) and ind == field_indent + 2:
                        i += 1
                        continue
                    break
            continue
        kept.append(line)
        i += 1

    return "\n".join(kept)


def _mentioned_skills(body: str, self_name: str) -> set[str]:
    return set(_re.findall(r"pax-[a-z][a-z0-9-]*", body)) - {self_name}


def _call_targets(body: str, self_name: str) -> set[str]:
    """本 skill 实际调用的 skill（排除元数据引用）。"""
    return _mentioned_skills(strip_metadata_fields(body), self_name)


# ----- 契约①：frontmatter 完整性 -----

@register_contract("frontmatter-completeness")
def check_frontmatter_completeness(family_root: Path) -> list[str]:
    violations: list[str] = []
    family = loader.load_family_schema(family_root=_root(family_root))
    required = family["contracts"]["required_frontmatter"]
    naming_re = _re.compile(family["contracts"]["naming"])
    for skill_dir in _iter_skill_dirs(family_root):
        text = (skill_dir / "SKILL.md").read_text(encoding="utf-8")
        fm, _ = _split_frontmatter(text)
        if fm is None:
            violations.append(
                f"{skill_dir.name}: invalid or missing frontmatter"
            )
            continue
        for key in required:
            if key not in fm:
                violations.append(
                    f"{skill_dir.name}: frontmatter missing '{key}'"
                )
        if not naming_re.match(fm.get("name", "")):
            violations.append(
                f"{skill_dir.name}: name violates naming contract"
            )
    return violations


# ----- 契约②：snapshot schema 合法性 -----

@register_contract("snapshot-schema-validity")
def check_snapshot_schema_validity(family_root: Path) -> list[str]:
    violations: list[str] = []
    schema_path = loader.family_paths(_root(family_root))["snapshot_schema"]
    if not schema_path.exists():
        return [f"missing {schema_path}"]
    with schema_path.open("r", encoding="utf-8") as f:
        schema = _json.load(f)
    try:
        jsonschema.Draft202012Validator.check_schema(schema)
    except jsonschema.SchemaError as exc:
        violations.append(f"snapshot schema invalid: {exc.message}")
    return violations


# ----- 契约③：skill 声明的快照字段必须存在于 snapshot schema -----

# 排除文件名/后缀形式的引用（schemas/snapshot.schema.json、pax-snapshot.yaml）
_SNAPSHOT_REF_RE = _re.compile(
    r"\bsnapshot\.([a-z_][a-z0-9_]*)(?:\.([a-z_][a-z0-9_]*))?"
)
_SNAPSHOT_REF_SKIP = {"schema", "yaml", "json"}


@register_contract("snapshot-field-conformance")
def check_snapshot_field_conformance(family_root: Path) -> list[str]:
    """每个 skill 提到/写入的 ``snapshot.<section>[.<field>]`` 必须能在
    schemas/snapshot.schema.json 中解析到。这是防止「skill 偷偷写了 schema
    没定义的字段」的机械约束——此前 8 处断裂正是因为缺了这条检查。
    """
    snapshot = loader.load_snapshot_schema(family_root=_root(family_root))
    props: dict = snapshot.get("properties", {})
    violations: set[str] = set()
    for name, _fm, body in _skill_docs(family_root):
        for match in _SNAPSHOT_REF_RE.finditer(body):
            section, sub = match.group(1), match.group(2)
            if section in _SNAPSHOT_REF_SKIP:
                continue
            if section not in props:
                violations.add(
                    f"{name}: 引用了 snapshot.{section}，"
                    f"但 snapshot.schema.json 无此顶层字段"
                )
                continue
            if sub is None:
                continue
            sub_props = props[section].get("properties")
            # 只声明了 {"type": "object"} 的段（如 diagnosis）不做二级校验
            if not sub_props:
                continue
            if sub not in sub_props:
                violations.add(
                    f"{name}: 引用了 snapshot.{section}.{sub}，"
                    f"但 schema 中 {section} 未声明该字段"
                )
    return sorted(violations)


# ----- 契约④：层间调用合法性 -----

def _allowed_calls(family_root: Path | None = None) -> set[tuple[str, str]]:
    """允许的层间调用方向，权威源是 versions.json 的 compatibility_matrix。"""
    versions = loader.load_versions(family_root=_root(family_root))
    matrix = versions.get("compatibility_matrix", {})
    return {
        (src, tgt)
        for src, targets in matrix.items()
        if not src.startswith("_") and isinstance(targets, list)
        for tgt in targets
    }


@register_contract("layer-call-legality")
def check_layer_call_legality(family_root: Path) -> list[str]:
    allowed = _allowed_calls(family_root)
    violations: list[str] = []
    skill_layers: dict[str, str] = {}
    for name, fm, _body in _skill_docs(family_root):
        if fm and "layer" in fm:
            skill_layers[name] = fm["layer"]
    for name, fm, body in _skill_docs(family_root):
        if fm is None:
            continue
        self_layer = fm.get("layer")
        # 只查前向调用边：`## 何时升级` 里的失败回退本就该指向更上游的层，
        # 用 compatibility_matrix 判它会误报（L1 测试失败退回 L1 plan 是设计
        # 要求的闭环，不是非法方向）。
        forward, _escalate = split_escalation_targets(
            strip_metadata_fields(body), name
        )
        for target_name in forward:
            target_layer = skill_layers.get(target_name)
            if target_layer is None:
                continue
            if (self_layer, target_layer) not in allowed:
                violations.append(
                    f"{name} ({self_layer}) references "
                    f"{target_name} ({target_layer}): forbidden direction"
                )
    return violations


# ----- 契约⑤：schema.layers 与实际成员一致 -----

@register_contract("layer-membership")
def check_layer_membership(family_root: Path) -> list[str]:
    """schemas/pax-family.schema.yaml 的 layers 枚举必须与 registry.json 一致。

    schema.layers 此前是没人读的死数据，L1 缺 5 个、L4 缺 1 个也无人发现。
    """
    family = loader.load_family_schema(family_root=_root(family_root))
    registry = loader.load_registry(family_root=_root(family_root))
    layers: dict = family.get("layers", {})
    non_runtime = set(family.get("non_runtime_layers", []))

    actual_suffixes = {
        d.name[len("pax-"):] for d in _iter_skill_dirs(family_root)
        if d.name.startswith("pax-")
    }
    declared: dict[str, str] = {}
    for layer, members in layers.items():
        for member in members:
            if member.endswith("*"):
                prefix = member[:-1]
                for suffix in actual_suffixes:
                    if suffix.startswith(prefix):
                        declared[f"pax-{suffix}"] = layer
            else:
                declared[f"pax-{member}"] = layer

    registered = {e["name"]: e.get("layer") for e in registry.get("skills", [])}
    violations: list[str] = []

    for name, layer in registered.items():
        want = declared.get(name)
        if want is None:
            violations.append(
                f"{name}: 注册为 {layer}，但未出现在 "
                f"schemas/pax-family.schema.yaml 的 layers 中"
            )
        elif want != layer:
            violations.append(
                f"{name}: registry layer={layer} != schema.layers={want}"
            )

    for layer, members in layers.items():
        if layer in non_runtime:
            continue
        for member in members:
            if member.endswith("*"):
                continue
            name = f"pax-{member}"
            if name not in registered:
                violations.append(
                    f"{name}: 在 schema.layers.{layer} 声明，但未注册到 registry.json"
                )
    return violations


# ----- 契约⑥：compatibility_matrix 自洽 -----

@register_contract("compatibility-matrix-consistency")
def check_compatibility_matrix_consistency(family_root: Path) -> list[str]:
    versions = loader.load_versions(family_root=_root(family_root))
    family = loader.load_family_schema(family_root=_root(family_root))
    registry = loader.load_registry(family_root=_root(family_root))
    violations: list[str] = []

    matrix = versions.get("compatibility_matrix")
    if not isinstance(matrix, dict) or not matrix:
        return ["versions.json: compatibility_matrix 缺失或为空对象"]

    layers = set(family.get("layers", {}).keys())
    registered = {e["name"] for e in registry.get("skills", [])}

    for src, targets in matrix.items():
        if src.startswith("_"):
            continue
        if src not in layers:
            violations.append(
                f"compatibility_matrix: 源层 {src} 不是 schema.layers 中已知的层"
            )
        if not isinstance(targets, list):
            violations.append(
                f"compatibility_matrix[{src}]: 必须是层名数组"
            )
            continue
        for tgt in targets:
            if tgt not in layers:
                violations.append(
                    f"compatibility_matrix[{src}]: 目标层 {tgt} 不是已知的层"
                )
            if tgt in family.get("non_runtime_layers", []):
                violations.append(
                    f"compatibility_matrix[{src}]: 不允许调用非运行时层 {tgt}"
                )

    flow = versions.get("main_flow", {}).get("path", [])
    for skill in flow:
        if skill not in registered:
            violations.append(
                f"main_flow: {skill} 不是 registry.json 中的已注册 skill"
            )
    # 主干链上的每一步都必须是可被前一步调用的方向
    for prev, cur in zip(flow, flow[1:]):
        prev_layer = next((e.get("layer") for e in registry.get("skills", [])
                           if e["name"] == prev), None)
        cur_layer = next((e.get("layer") for e in registry.get("skills", [])
                          if e["name"] == cur), None)
        if prev_layer and cur_layer and (prev_layer, cur_layer) not in _allowed_calls(family_root):
            violations.append(
                f"main_flow: {prev} ({prev_layer}) → {cur} ({cur_layer}) "
                f"不在 compatibility_matrix 允许的方向内"
            )
    return violations


# ----- 契约⑦：版本一致性 -----

@register_contract("version-consistency")
def check_version_consistency(family_root: Path) -> list[str]:
    versions_path = loader.family_paths(_root(family_root))["versions"]
    if not versions_path.exists():
        return ["missing pax-ops/versions.json"]
    with versions_path.open("r", encoding="utf-8") as f:
        versions = _json.load(f)
    known = versions.get("skills", {})
    violations: list[str] = []
    for name, fm, _body in _skill_docs(family_root):
        if fm is None:
            continue
        if name not in known:
            violations.append(
                f"{name}: not listed in pax-ops/versions.json"
            )
            continue
        if known[name].get("version") != fm.get("version"):
            violations.append(
                f"{name}: SKILL.md version {fm.get('version')!r} != "
                f"versions.json {known[name].get('version')!r}"
            )
    return violations


# ----- 回退边（失败升级）与前向调用边的区分 -----

ESCALATE_HEADING = "## 何时升级"
_ESCALATE_ITEM_RE = _re.compile(r"^\s*[-*]\s")
# 真调用声明的形态：中文动词 + 反引号包裹的 skill 名
# （`调用 \`pax-gate\``、`委托 \`pax-advisor\``、`插入 \`pax-test\``）。
# 数据引用则不带这种标记：`pax-plan.rollback_strategy`、`pax-family.schema.yaml`、
# `pax-ops/versions.json`。靠这个区分「调用边」与「提及边」。
_CALL_VERB_RE = _re.compile(
    r"(?:调用|委托|委派|挂载|插入|路由到|路由至|交由|转交|升级至|升级到|进入)"
    r"[^`\n]{0,12}`(pax-[a-z][a-z0-9-]*)`"
)
# 路由表里裸名成组出现（`[clarify, plan, execute, review]`）也算声明
_ROUTE_GROUP_RE = _re.compile(r"`\[([a-z][^\]\n]*)\]`")
# 形如 `[x]` 的 checklist 记号与状态词，不是 skill 名
_NON_ROUTE_TOKENS = {"x", "v", "ok", "pass", "none", "all"}


def _declared_call_targets(line: str) -> set[str]:
    """一行里被显式声明为「调用」的 skill 名。"""
    return set(_CALL_VERB_RE.findall(line))


def split_escalation_targets(body: str, self_name: str) -> tuple[set[str], set[str]]:
    """把 skill 正文里的提及分成（前向调用边, 失败回退边）。

    失败回退边统一声明在 `## 何时升级` 段落里——这是家族里 13 个 skill
    共同遵守的结构约定（pax-test 的「覆盖率不达标 → pax-plan」、
    pax-execute 的「需要独立评审 → pax-review」等）。

    为什么要分开：`no-cycles` 判的是「前向编排不得成环」。但测试失败
    退回 plan、评审 needs_fix 退回 execute 属于**失败回退**，是设计上
    必需的闭环，不参与前向环检测。两者混在一起判，任何「阶段失败就回退」
    的设计都会被报成循环依赖。

    返回 ``(forward, escalate)``。
    """
    lines = body.split("\n")
    forward: set[str] = set()
    escalate: set[str] = set()
    in_escalate = False

    for line in lines:
        if line.lstrip().startswith(ESCALATE_HEADING):
            in_escalate = True
            continue
        # 遇到下一个同级别标题即退出该段落
        if in_escalate and line.startswith("#") and not line.startswith(ESCALATE_HEADING):
            in_escalate = False

        if in_escalate and _ESCALATE_ITEM_RE.match(line):
            escalate |= set(_re.findall(r"pax-[a-z][a-z0-9-]*", line)) - {self_name}
            continue

        declared = _declared_call_targets(line)
        for group in _ROUTE_GROUP_RE.findall(line):
            names = [n for n in _re.findall(r"[a-z][a-z0-9-]*", group)
                     if n not in _NON_ROUTE_TOKENS]
            # 至少两个裸名才算路由组：`[clarify, plan, execute]` 是路由，
            # `[x]` 是 checklist 记号（pax-execute / pax-test 里都有
            # 「只写 `[x]` 不算证据」这类句子）。
            if len(names) >= 2:
                declared |= set(names)
        if declared:
            forward |= {f"pax-{d}" if not d.startswith("pax-") else d
                        for d in declared} - {self_name}

    return forward, escalate


# ----- 契约⑧：无循环依赖 -----

def _extract_call_graph(family_root: Path) -> dict[str, set[str]]:
    graph: dict[str, set[str]] = {}
    for name, fm, body in _skill_docs(family_root):
        if fm is None:
            continue
        forward, _escalate = split_escalation_targets(
            strip_metadata_fields(body), name
        )
        graph[name] = forward
    return graph


def _extract_escalation_graph(family_root: Path) -> dict[str, set[str]]:
    """收集失败回退边，仅用于报告——它们不参与环检测。"""
    graph: dict[str, set[str]] = {}
    for name, fm, body in _skill_docs(family_root):
        if fm is None:
            continue
        _forward, escalate = split_escalation_targets(
            strip_metadata_fields(body), name
        )
        if escalate:
            graph[name] = escalate
    return graph


def _find_cycles(graph: dict[str, set[str]]) -> list[list[str]]:
    cycles: list[list[str]] = []
    seen_global: set[tuple[str, ...]] = set()
    visited: set[str] = set()
    path: list[str] = []

    def dfs(node: str):
        if node in path:
            cyc = tuple(path[path.index(node):])
            if cyc not in seen_global:
                seen_global.add(cyc)
                cycles.append(list(cyc) + [node])
            return
        if node in visited:
            return
        visited.add(node)
        path.append(node)
        for nxt in sorted(graph.get(node, ())):
            if nxt in graph:
                dfs(nxt)
        path.pop()

    for node in sorted(graph):
        visited.clear()
        path.clear()
        dfs(node)
    return cycles


@register_contract("no-cycles")
def check_no_cycles(family_root: Path) -> list[str]:
    graph = _extract_call_graph(family_root)
    cycles = _find_cycles(graph)
    return [f"cycle detected: {' -> '.join(c)}" for c in cycles]


# ----- 契约⑨：跳过审计 -----

SKIP_AUDIT_KEYWORDS = ("skip_reason", "跳过留痕", "跳过理由")


@register_contract("skip-audit")
def check_skip_audit(family_root: Path) -> list[str]:
    violations: list[str] = []
    for name, fm, body in _skill_docs(family_root):
        if fm is None:
            continue
        if not fm.get("optional", False):
            continue
        if not any(k in body for k in SKIP_AUDIT_KEYWORDS):
            violations.append(
                f"{name}: optional skill must document "
                f"skip_reason (跳过留痕契约)"
            )
    return violations


# ----- 契约⑩：门禁行为 -----

GATE_KEYWORDS = ("前置门禁", "前置条件", "未通过", "不满足", "禁止", "降级")


@register_contract("gate-behavior")
def check_gate_behavior(family_root: Path) -> list[str]:
    violations: list[str] = []
