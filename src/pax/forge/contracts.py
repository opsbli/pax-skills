# ----- 契约⑬：L0 入口的路由声明覆盖 registry 全部运行时成员 -----

_ROUTING_TABLE_HEADER = _re.compile(r"^\|\s*一级意图\s*\|", _re.M)
_OPTIONAL_TABLE_HEADER = _re.compile(r"^\|\s*Skill\s*\|\s*层级\s*\|", _re.M)


def _table_segment(body: str, header_re: _re.Pattern[str]) -> str | None:
    """截取指定表头的 Markdown 表格连续行。

    锚点是表头而不是任何 `[...]`——后者散布全文，无法区分
    「路由表里的一格」与「示例里的一个数组」。
    """
    m = header_re.search(body)
    if m is None:
        return None
    lines = body[m.start():].split("\n")
    rows = [lines[0]]
    for line in lines[1:]:
        if not line.lstrip().startswith("|"):
            break
        rows.append(line)
    return "\n".join(rows)


def _routing_table_segment(body: str) -> str | None:
    """主路由表区段：`| 一级意图 | 二级意图 | ... |`。"""
    return _table_segment(body, _ROUTING_TABLE_HEADER)


def _declared_routing_segment(body: str) -> str | None:
    """入口的全部路由声明 = 主路由表 ∪ 可选 skill 表。

    pax-orchestrate 有两张表：`代表路由组合`（意图 → 路由）与
    `除主路由外，以下可选 Skill 可在特定条件下被调用`（skill → 触发条件）。
    monitor / rollback / deploy / learn / design / research / prototype-to-prd
    全部登记在第二张表。只校验第一张会把它们全判成缺口。
    """
    parts = [
        seg for seg in (
            _table_segment(body, _ROUTING_TABLE_HEADER),
            _table_segment(body, _OPTIONAL_TABLE_HEADER),
        )
        if seg is not None
    ]
    return "\n".join(parts) if parts else None


@register_contract("router-coverage")
def check_router_coverage(family_root: Path) -> list[str]:
    """pax-orchestrate 的路由表必须覆盖所有「入口承诺路由」的 skill。

    路由表此前只是一张「代表路由组合」的示例表，漏掉的 skill 不会被任何
    契约发现——新增 skill 后它既不在表里，也没有检查会红。

    只校验「入口承诺路由的 skill 是否都被提及」，不校验顺序或触发条件：
    后者是语义判断，不属于可机器判定的范围。

    不校验 L2/L3/L4 与被上层内嵌的门禁段：
    - L3 worker 由上层 skill 按 delegation_target 委派，不走入口路由；
    - L4 是用户直调工具（pax-init/pax-handoff），其description 已自述
      「由用户直接调用，不认领编排路由落点」；
    - L2 advisor 由 pax-analyze 在升级路径中委托；
    - pax-gate 是评审/部署阶段内嵌的门禁段，其 description 自述
      「由评审阶段与部署阶段在发布前调用」，不是独立路由落点。
    强行要求它们出现在入口路由表里会制造无法满足的假失败。
    """
    family = loader.load_family_schema(family_root=_root(family_root))
    registry = loader.load_registry(family_root=_root(family_root))
    non_runtime = set(family.get("non_runtime_layers", []))
    routed_layers = {"L0", "L1"}
    # 内嵌门禁段：被上游阶段在自己的流程里触发，不作为独立路由落点。
    # 取自 pax-gate 自身 description 的「由评审阶段与部署阶段在发布前调用」。
    embedded = {"pax-gate"}

    entry_name = "pax-orchestrate"
    body = None
    for name, _fm, doc_body in _skill_docs(family_root):
        if name == entry_name:
            body = doc_body
            break
    if body is None:
        return [f"{entry_name}: 未找到 SKILL.md，无法校验路由表"]

    # 只取「路由声明」区段做覆盖判定，不能扫全文：
    # description / 前置条件 / 示例里处处提到各 skill 名（pax-clarify 单独
    # 就出现 7 次），扫全文会让契约在任何路由表缺失下都判绿——没有 teeth。
    table = _declared_routing_segment(body)
    if table is None:
        return [
            f"{entry_name}: 未找到路由声明区段（形如 "
            f"`| 一级意图 | ... |` 或 `| Skill | 层级 | ... |` 的 Markdown 表格），"
            f"无法校验覆盖"
        ]

    # 路由表同时接受裸名（clarify）与全名（pax-clarify）两种写法。
    mentioned = set(_re.findall(r"pax-[a-z][a-z0-9-]*", table))
    bare = {n[len("pax-"):] for n in mentioned}
    bare |= {
        m
        for group in _re.findall(r"\[([a-z][^\]\n]*)\]", table)
        for m in _re.findall(r"[a-z][a-z0-9-]*", group)
    }

    violations: list[str] = []
    for entry in registry.get("skills", []):
        name = entry.get("name")
        layer = entry.get("layer")
        if not name or layer in non_runtime or layer not in routed_layers:
            continue
        if name == entry_name or name in embedded:
            # 入口自己必然不在自己的路由表里；内嵌门禁段不走独立路由
            continue
        short = name[len("pax-"):]
        if name not in mentioned and short not in bare:
            violations.append(
                f"{name} (layer={layer}) 已注册且属于入口承诺路由的层"
                f"（{'/'.join(sorted(routed_layers))}），但未出现在 "
                f"{entry_name} 的路由表中，该 skill 不会被编排调用"
            )
    return violations



# ----- 契约⑭：委派隔离与依赖图声明 -----

# 真委派声明的形态：动词 + 反引号包裹的 skill 名，或显式的委派函数。
# 不能只靠「出现 subagent 字样」判定——pax-plan 的 execution_strategy
# 枚举里就有 "subagent" 这个取值，它不是委派实现。
_DELEGATION_RE = _re.compile(
    r"(?:委派|委托|delegate|subagent|子\s*agent)"
    r"[^`\n]{0,16}`(pax-[a-z][a-z0-9-]*)`"
    r"|delegate_to_\w+"
    r"|\bspawn_\w+",
    _re.IGNORECASE,
)
# 只读目标不需要隔离：委托只读顾问不会写工作树。
_READONLY_TARGETS = ("pax-advisor", "pax-council", "pax-docs")
_ISOLATION_TOKENS = (
    "worktree", "隔离", "独立分支", "isolated", "独立工作区",
)


@register_contract("delegation-isolation")
def check_delegation_isolation(family_root: Path) -> list[str]:
    """具备写委派能力的 skill 必须声明隔离手段。

    `pax-worker-implement` 的 Execution Contract 要求「必须在 isolated FS /
    network 下运行」，但没说隔离怎么来；`pax-execute` 的 delegate_to_worker
    也没有说明工作区边界。没有隔离的委派等于多个 agent 并行写同一个工作树。

    两条豁免，因为它们不需要隔离：
    - 只读目标（`pax-advisor` / `pax-council` / `pax-docs`）——委托出去不写文件；
    - 仅把 "subagent" 作为 `execution_strategy` 的枚举值（pax-plan）——
      那是策略取值，不是委派实现。

    只检查「是否声明了隔离手段」，不判定隔离方式是否充分——
    后者属于运行时语义，机器无法判定。
    """
    violations: list[str] = []
    for name, fm, body in _skill_docs(family_root):
        if fm is None:
            continue
        # 只管真正提供写委派能力的 skill：显式委派到非只读目标，
        # 或本身就是被委派的 worker。
        if fm.get("layer") == "L3":
            delegates = True
        else:
            matches = _DELEGATION_RE.findall(body)
            # delegate_to_xxx / spawn_xxx 这类函数名不带目标，按写委派处理
            targets = [t for t in matches if isinstance(t, str) and t]
            has_func = any(m in body for m in ("delegate_to_", "spawn_"))
            delegates = has_func or any(
                t not in _READONLY_TARGETS for t in targets
            )
        is_worker = fm.get("layer") == "L3"
        if not (delegates or is_worker):
            continue

        # Execution Contract 与委派段落里出现了隔离手段即通过
        isolated = any(
            tok in body for tok in _ISOLATION_TOKENS
        )
        if not isolated:
            violations.append(
                f"{name}: 声明了委派/worker 能力但未声明隔离手段"
                f"（可用措辞：{' / '.join(_ISOLATION_TOKENS[:4])}）"
            )
    return violations


@register_contract("step-dependency-acyclic")
def check_step_dependency_acyclic(family_root: Path) -> list[str]:
    """snapshot.plan.dependencies 必须是可解析的无环边集。

    `pax-execute` 的执行顺序依赖 `topological_sort(steps, plan.dependencies)`，
    但该函数在文档里从未定义、dependencies 的结构也从未在 schema 约束——
    依赖图因此可能成环，而成环的依赖图会让执行顺序无法确定（谁先跑）。

    本契约检查两件可机判定的事：
    1. 每条边必须有 from / to，且两端都能在 steps 里找到；
    2. 整张图必须无环。
    它读取家族当前的 snapshot（若有）；没有 snapshot 时跳过——契约不能
    对着不存在的运行产物判红。
    """
    from pax.forge.validator import _split_frontmatter  # noqa: F401

    schema_path = loader.family_paths(_root(family_root))["snapshot_schema"]
    if not schema_path.exists():
        return []

    # 从 skill 文档里抽出 plan.dependencies 的示例边做结构校验：
    # 真实 snapshot 是运行产物、不入库，因此契约校验的是「文档声明的
    # 依赖边是否结构合法且无环」。
    edges: list[tuple[str, str]] = []
    step_ids: set[str] = set()
    for name, fm, body in _skill_docs(family_root):
        if fm is None:
            continue
        step_ids |= set(_re.findall(r"^\s*-\s*id:\s*([A-Za-z0-9_.\-]+)", body, _re.M))
        edges += _parse_dependency_edges(body)

    if not edges:
        return []

    violations: list[str] = []
    for src, dst in edges:
        if step_ids and src not in step_ids:
            violations.append(f"dependency edge {src} -> {dst}: 起点 {src} 未在任何 step 中声明")
        if step_ids and dst not in step_ids:
            violations.append(f"dependency edge {src} -> {dst}: 终点 {dst} 未在任何 step 中声明")

    if steps := _find_cycle(list(edges)):
        violations.append(
            "plan.dependencies 存在环，无法确定执行顺序: " + " -> ".join(steps)
        )
    return violations


# 同时支持三种 YAML 写法：行内 `{from: A, to: B}`、同行 `- from: A, to: B`、
# 跨行（from 与 to 分属两行，pax-plan 的 dependencies 用的就是这种）。
_DEP_EDGE_RE = _re.compile(
    r"from\s*:\s*[\"']?([A-Za-z0-9_.\-]+)[\"']?\s*,?\s*\n?\s*"
    r"to\s*:\s*[\"']?([A-Za-z0-9_.\-]+)[\"']?",
    _re.M,
)


def _parse_dependency_edges(body: str) -> list[tuple[str, str]]:
    return [(m.group(1), m.group(2)) for m in _DEP_EDGE_RE.finditer(body)]


def _find_cycle(edges: list[tuple[str, str]]) -> list[str] | None:
    """返回第一个环的节点序列；无环返回 None。"""
    adj: dict[str, list[str]] = {}
    for src, dst in edges:
        adj.setdefault(src, []).append(dst)
    state: dict[str, int] = {}  # 0=未访问 1=在栈上 2=已完成
    stack: list[str] = []

    def visit(node: str) -> list[str] | None:
        state[node] = 1
        stack.append(node)
        for nxt in adj.get(node, []):
            if state.get(nxt) == 1:
                return stack[stack.index(nxt):] + [nxt]
            if state.get(nxt, 0) == 0:
                if (found := visit(nxt)) is not None:
                    return found
        stack.pop()
        state[node] = 2
        return None

    for node in list(adj):
        if state.get(node, 0) == 0:
            if (found := visit(node)) is not None:
                return found
    return None